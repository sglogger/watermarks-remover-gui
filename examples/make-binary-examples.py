#!/usr/bin/env python3
"""Generate the binary sample files (PNG and DOCX) used to try the GUI.

They are built here rather than committed so that the repository carries no
opaque binaries. Both files are minimal but genuinely valid, and both carry the
kind of AI-provenance metadata the engine looks for.

    python3 examples/make-binary-examples.py
"""

from __future__ import annotations

import struct
import zipfile
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _png_chunk(kind: bytes, payload: bytes) -> bytes:
    return (
        struct.pack(">I", len(payload))
        + kind
        + payload
        + struct.pack(">I", zlib.crc32(kind + payload) & 0xFFFFFFFF)
    )


def write_png(path: Path, width: int = 16, height: int = 16) -> None:
    """A tiny solid-colour PNG carrying tEXt metadata that names an AI tool."""
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    # One filter byte per row, then RGB pixels.
    raw = b"".join(b"\x00" + bytes([0x2F, 0x5F, 0xD0]) * width for _ in range(height))

    text_chunks = b"".join(
        _png_chunk(b"tEXt", key + b"\x00" + value)
        for key, value in (
            (b"Software", b"SampleDiffusion 1.0"),
            (b"Comment", b"Generated by an AI image model"),
            (b"Author", b"watermarks-remover-gui example"),
        )
    )

    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", header)
        + text_chunks
        + _png_chunk(b"IDAT", zlib.compress(raw, 9))
        + _png_chunk(b"IEND", b"")
    )


